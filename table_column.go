package pgmo

import (
	"context"
	"fmt"
)

// ============================================================
// Columns
// ============================================================
//
// table_column.go reads a table's columns (PLAN.md P4.4): pg_attribute
// with its default (pg_attrdef), type, collation, ACL and comment, in one
// statement. System columns (ctid, xmin…; attnum ≤ 0) and dropped ones are
// not read.

// IdentityKind is pg_attribute.attidentity: whether a column is an identity
// column, and which.
type IdentityKind string

const (
	IdentityNone      IdentityKind = ""
	IdentityAlways    IdentityKind = "a" // GENERATED ALWAYS AS IDENTITY
	IdentityByDefault IdentityKind = "d" // GENERATED BY DEFAULT AS IDENTITY
)

// GeneratedKind is pg_attribute.attgenerated: whether a column is computed
// from the others, and how.
type GeneratedKind string

const (
	GeneratedNone    GeneratedKind = ""
	GeneratedStored  GeneratedKind = "s" // GENERATED ALWAYS AS (…) STORED: computed on write
	GeneratedVirtual GeneratedKind = "v" // GENERATED ALWAYS AS (…) VIRTUAL: computed on read, 18+
)

// StorageKind is pg_attribute.attstorage: how a column's values are stored
// once they grow large (ALTER COLUMN … SET STORAGE).
type StorageKind string

const (
	StoragePlain    StorageKind = "p" // inline, uncompressed: fixed-length types
	StorageExternal StorageKind = "e" // out of line, uncompressed
	StorageMain     StorageKind = "m" // inline, compressed; out of line only as a last resort
	StorageExtended StorageKind = "x" // compressed, then out of line
)

// String names the storage as SET STORAGE spells it: PLAIN, EXTERNAL,
// MAIN, EXTENDED; an unknown code reads StorageKind("x").
func (s StorageKind) String() string {
	switch s {
	case StoragePlain:
		return "PLAIN"
	case StorageExternal:
		return "EXTERNAL"
	case StorageMain:
		return "MAIN"
	case StorageExtended:
		return "EXTENDED"
	}
	return fmt.Sprintf("StorageKind(%q)", string(s))
}

// Column is one column of a table.
type Column struct {
	// Number is the column's attnum: its position as created, 1-based. A
	// dropped column keeps its number, so they can skip.
	Number int

	Name string

	// TypeOID is the column's type (atttypid).
	TypeOID OID

	// Type is the type as a column definition writes it, its modifier
	// included: format_type's name ("numeric(18,2)", "character
	// varying(40)", "text[]") for a type in pg_catalog, and schema-qualified
	// for any other ("app.mood[]", "public.vector(3)") whatever the
	// session's search_path.
	Type string

	// NotNull is attnotnull: the column refuses NULL. From 18 the
	// constraint is also a named row in Table.Constraints.
	NotNull bool

	// Default is the DEFAULT expression as pg_get_expr renders it, empty
	// for none or for a generated column (GenerationExpression).
	Default string

	Identity IdentityKind

	Generated GeneratedKind

	// GenerationExpression is a generated column's expression, empty for
	// any other column.
	GenerationExpression string

	// Collation is the column's collation when it is not its type's own —
	// a COLLATE clause — and zero otherwise (a non-collatable type
	// included).
	Collation ObjectName

	Storage StorageKind

	// StatisticsTarget is ALTER COLUMN … SET STATISTICS's value, -1 for
	// none (the server's default_statistics_target applies).
	StatisticsTarget int

	// IsLocal reports a column defined by the table itself; InheritCount
	// the number of parents it is inherited from. A column both defined
	// and inherited has both.
	IsLocal      bool
	InheritCount int

	// Privileges are the column's own ACL — GRANT SELECT (col) … — per
	// grantee in stored order; nil when none was granted. Privileges
	// granted on the whole table are on Table.Privileges.
	Privileges []PrivilegeGrant

	// Comment is COMMENT ON COLUMN's text, empty for none.
	Comment string
}

// columnTypeName is the text expression naming the type of the column a,
// with its modifier (typeNameWithModifier).
var columnTypeName = typeNameWithModifier("tn", "ft")

// columnsQuery reads the columns of the table $1 in attnum order.
var columnsQuery = `SELECT a.attnum::integer, a.attname::pg_catalog.text, a.atttypid,
	` + columnTypeName + `,
	a.attnotnull,
	CASE WHEN a.attgenerated = '' THEN COALESCE(pg_catalog.pg_get_expr(ad.adbin, ad.adrelid), '') ELSE '' END,
	a.attidentity::pg_catalog.text, a.attgenerated::pg_catalog.text,
	CASE WHEN a.attgenerated <> '' THEN COALESCE(pg_catalog.pg_get_expr(ad.adbin, ad.adrelid), '') ELSE '' END,
	CASE WHEN a.attcollation <> t.typcollation THEN COALESCE(cn.nspname::pg_catalog.text, '') ELSE '' END,
	CASE WHEN a.attcollation <> t.typcollation THEN COALESCE(co.collname::pg_catalog.text, '') ELSE '' END,
	a.attstorage::pg_catalog.text, COALESCE(a.attstattarget, -1)::integer,
	a.attislocal, a.attinhcount::integer,
	` + aclColumns("p") + `,
	COALESCE(pg_catalog.col_description(a.attrelid, a.attnum), '')
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
JOIN pg_catalog.pg_namespace tn ON tn.oid = t.typnamespace
CROSS JOIN LATERAL (SELECT pg_catalog.format_type(a.atttypid, a.atttypmod) AS name) AS ft
LEFT JOIN pg_catalog.pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
LEFT JOIN pg_catalog.pg_collation co ON co.oid = a.attcollation
LEFT JOIN pg_catalog.pg_namespace cn ON cn.oid = co.collnamespace
` + aclLateral("a.attacl", "p") + `
WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`

// scanColumn builds a *Column from one columnsQuery row.
func scanColumn(scan func(...any) error) (*Column, error) {
	c := &Column{}
	var identity, generated, storage string
	var acl privilegeArrays
	dest := []any{&c.Number, &c.Name, &c.TypeOID, &c.Type, &c.NotNull, &c.Default,
		&identity, &generated, &c.GenerationExpression, &c.Collation.Schema, &c.Collation.Name,
		&storage, &c.StatisticsTarget, &c.IsLocal, &c.InheritCount}
	dest = append(dest, acl.dest()...)
	dest = append(dest, &c.Comment)
	if err := scan(dest...); err != nil {
		return nil, err
	}
	c.Identity, c.Generated, c.Storage = IdentityKind(identity), GeneratedKind(generated), StorageKind(storage)
	var err error
	c.Privileges, err = acl.all()
	return c, err
}

// Columns reads the table's columns in attnum order. A TableRef is refused
// (ErrHandleNotLoaded); a table dropped since it was read has none.
func (t *Table) Columns(ctx context.Context) ([]*Column, error) {
	if err := t.requireLoaded("list columns of table"); err != nil {
		return nil, err
	}
	q, err := t.on(ctx)
	if err != nil {
		return nil, err
	}
	return scanRows(ctx, q, "list columns of table "+t.QualifiedName(), scanColumn, columnsQuery, t.OID)
}
