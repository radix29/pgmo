"""Generate tables.go: the RFC 3454 tables SASLprep (RFC 4013) uses, from
Python's stringprep module, which holds them as published (Unicode 3.2).

They are the tables PostgreSQL's src/common/saslprep.c carries, code point
for code point: checked against PostgreSQL 15's and 18's saslprep.c when
generated (2026-11-21). TestSASLprepTableEdges pins a sample of their edges.

Run from this directory with: python3 gen_tables.py
Only the Python standard library is needed; no network access is required.
"""

from pathlib import Path
import stringprep
from unicodedata import ucd_3_2_0

assert ucd_3_2_0.unidata_version == "3.2.0"

TABLES = [
    ("nonASCIISpace", "C.1.2: non-ASCII space characters, mapped to U+0020.",
     stringprep.in_table_c12),
    ("mappedToNothing", "B.1: commonly mapped to nothing.",
     stringprep.in_table_b1),
    ("prohibited", "the prohibited output of SASLprep: C.1.2, C.2.1, C.2.2,\n// C.3, C.4, C.5, C.6, C.7, C.8 and C.9.",
     lambda c: stringprep.in_table_c12(c) or stringprep.in_table_c21_c22(c)
     or stringprep.in_table_c3(c) or stringprep.in_table_c4(c)
     or stringprep.in_table_c5(c) or stringprep.in_table_c6(c)
     or stringprep.in_table_c7(c) or stringprep.in_table_c8(c)
     or stringprep.in_table_c9(c)),
    ("unassigned", "A.1: unassigned in Unicode 3.2.", stringprep.in_table_a1),
    ("randALCat", "D.1: characters with bidirectional property R or AL.",
     stringprep.in_table_d1),
    ("lCat", "D.2: characters with bidirectional property L.",
     stringprep.in_table_d2),
]


def ranges(pred):
    first = None
    for code in range(0x110000):
        if pred(chr(code)):
            if first is None:
                first = code
        elif first is not None:
            yield first, code - 1
            first = None
    if first is not None:
        yield first, 0x10FFFF


lines = [
    "// Code generated by gen_tables.py; DO NOT EDIT.",
    "",
    "package scram",
    "",
    'import "unicode"',
    "",
    "//go:generate python3 gen_tables.py",
]
for name, doc, pred in TABLES:
    rs = list(ranges(pred))
    lines += ["", f"// {name} is RFC 3454 table {doc}", f"var {name} = &unicode.RangeTable{{"]
    r16 = [r for r in rs if r[1] < 0x10000]
    r32 = [r for r in rs if r[0] >= 0x10000]
    assert len(r16) + len(r32) == len(rs), name  # no range spans 0xFFFF/0x10000
    if r16:
        lines.append("\tR16: []unicode.Range16{")
        lines += [f"\t\t{{0x{a:04x}, 0x{b:04x}, 1}}," for a, b in r16]
        lines.append("\t},")
    if r32:
        lines.append("\tR32: []unicode.Range32{")
        lines += [f"\t\t{{0x{a:04x}, 0x{b:04x}, 1}}," for a, b in r32]
        lines.append("\t},")
    lo = sum(1 for a, b in r16 if b <= 0xFF)
    if lo:
        lines.append(f"\tLatinOffset: {lo},")
    lines.append("}")
lines.append("")
Path(__file__).with_name("tables.go").write_text("\n".join(lines), encoding="utf-8")
