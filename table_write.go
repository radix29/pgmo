// AddConstraint adds the constraint c (ALTER TABLE … ADD). NOT VALID skips
// checking the existing rows of a foreign key or check; NOT ENFORCED is
// 18+ (ErrUnsupportedVersion before). Nothing is mirrored: read Constraints
// again.
func (t *Table) AddConstraint(ctx context.Context, c ConstraintSpec) error {
	return t.alter(ctx, "add constraint to", func() (string, error) {
		def, err := c.definition(int(t.db.server.version))
		return "ADD " + def, err
	})
}

// DropConstraint drops the constraint name (ALTER TABLE … DROP CONSTRAINT),
// with CASCADE when opts.Cascade — which drops the foreign keys depending on
// a key's index.
func (t *Table) DropConstraint(ctx context.Context, name string, opts DropOptions) error {
	if name == "" {
		return invalidf("pgmo: drop constraint: no name")
	}
	return t.alter(ctx, "drop constraint "+pgsql.QuoteIdent(name)+" of", fixed("DROP CONSTRAINT "+pgsql.QuoteIdent(name)+opts.clause()))
}

// RenameConstraint renames the constraint name to newName (ALTER TABLE …
// RENAME CONSTRAINT); a key's index is renamed with it.
func (t *Table) RenameConstraint(ctx context.Context, name, newName string) error {
	if name == "" || newName == "" {
		return invalidf("pgmo: rename constraint: both names are required")
	}
	return t.alter(ctx, "rename constraint "+pgsql.QuoteIdent(name)+" of", fixed("RENAME CONSTRAINT "+pgsql.QuoteIdent(name)+" TO "+pgsql.QuoteIdent(newName)))
}

// ValidateConstraint checks the existing rows against the NOT VALID foreign
// key or check name, and marks it validated (ALTER TABLE … VALIDATE
// CONSTRAINT).
func (t *Table) ValidateConstraint(ctx context.Context, name string) error {
	if name == "" {
		return invalidf("pgmo: validate constraint: no name")
	}
	return t.alter(ctx, "validate constraint "+pgsql.QuoteIdent(name)+" of", fixed("VALIDATE CONSTRAINT "+pgsql.QuoteIdent(name)))
}

// SetConstraintComment sets the constraint name's comment (COMMENT ON
// CONSTRAINT … ON table), "" removing it.
func (t *Table) SetConstraintComment(ctx context.Context, name, text string) error {
	if name == "" {
		return invalidf("pgmo: comment on constraint: no name")
	}
	verb := "comment on constraint " + pgsql.QuoteIdent(name) + " of"
	o, err := t.ddl(verb)
	if err != nil {
		return err
	}
	return o.do(ctx, verb, commentStatement("CONSTRAINT "+pgsql.QuoteIdent(name)+" ON "+o.name, text))
}
