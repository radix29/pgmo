// AddColumn adds the column c (ALTER TABLE … ADD COLUMN). A table holds no
// columns, so nothing is mirrored: read Columns again.
func (t *Table) AddColumn(ctx context.Context, c ColumnSpec) error {
	return t.alter(ctx, "add column to", func() (string, error) {
		def, err := c.definition(int(t.db.server.version))
		return "ADD COLUMN " + def, err
	})
}

// DropColumn drops the column name (ALTER TABLE … DROP COLUMN), with CASCADE
// when opts.Cascade — which drops the views and constraints using it.
func (t *Table) DropColumn(ctx context.Context, name string, opts DropOptions) error {
	if name == "" {
		return invalidf("pgmo: drop column: no name")
	}
	return t.alter(ctx, "drop column "+pgsql.QuoteIdent(name)+" of", fixed("DROP COLUMN "+pgsql.QuoteIdent(name)+opts.clause()))
}

// RenameColumn renames the column name to newName (ALTER TABLE … RENAME
// COLUMN).
func (t *Table) RenameColumn(ctx context.Context, name, newName string) error {
	if name == "" || newName == "" {
		return invalidf("pgmo: rename column: both names are required")
	}
	return t.alter(ctx, "rename column "+pgsql.QuoteIdent(name)+" of", fixed("RENAME COLUMN "+pgsql.QuoteIdent(name)+" TO "+pgsql.QuoteIdent(newName)))
}

// ColumnChanges is a partial ALTER TABLE … ALTER COLUMN: each field set is
// one subcommand, all of them in one statement; the rest are left as they
// are.
type ColumnChanges struct {
	// Type is SET DATA TYPE's type as SQL, written as given; Collation and
	// Using are its COLLATE and USING (the conversion expression, as SQL),
	// and are refused without it. The server rewrites the table when the
	// type's storage changes.
	Type      string
	Collation ObjectName
	Using     string

	// Default is SET DEFAULT's expression as SQL; "" is DROP DEFAULT.
	Default *string

	// NotNull is SET NOT NULL (true, which scans the table) or DROP NOT
	// NULL (false).
	NotNull *bool

	// StatisticsTarget is SET STATISTICS: the planner's sample size for the
	// column, -1 for default_statistics_target.
	StatisticsTarget *int

	// Storage is SET STORAGE: how its large values are kept; "" leaves it.
	Storage StorageKind
}

// actions are c's ALTER COLUMN subcommands for the column col (quoted), or
// the refusal of a change that cannot be written.
func (c ColumnChanges) actions(col string) ([]string, error) {
	if c.Type == "" && (c.Collation.Name != "" || c.Using != "") {
		return nil, invalidf("COLLATE and USING are part of a type change; Type is empty")
	}
	alter := "ALTER COLUMN " + col + " "
	var acts []string
	if c.Type != "" {
		a := alter + "SET DATA TYPE " + c.Type
		if c.Collation.Name != "" {
			a += " COLLATE " + c.Collation.QualifiedName()
		}
		if c.Using != "" {
			a += " USING " + c.Using
		}
		acts = append(acts, a)
	}
	if c.Default != nil {
		if *c.Default == "" {
			acts = append(acts, alter+"DROP DEFAULT")
		} else {
			acts = append(acts, alter+"SET DEFAULT "+*c.Default)
		}
	}
	if c.NotNull != nil {
		if *c.NotNull {
			acts = append(acts, alter+"SET NOT NULL")
		} else {
			acts = append(acts, alter+"DROP NOT NULL")
		}
	}
	if c.StatisticsTarget != nil {
		if *c.StatisticsTarget < -1 {
			return nil, invalidf("statistics target %d; it is -1 (the default) or more", *c.StatisticsTarget)
		}
		acts = append(acts, alter+"SET STATISTICS "+strconv.Itoa(*c.StatisticsTarget))
	}
	switch c.Storage {
	case "":
	case StoragePlain, StorageExternal, StorageMain, StorageExtended:
		acts = append(acts, alter+"SET STORAGE "+c.Storage.String())
	default:
		return nil, invalidf("unknown storage %q", string(c.Storage))
	}
	return acts, nil
}

// AlterColumn applies every change set on c to the column name, in one ALTER
// TABLE. An empty c sends nothing.
func (t *Table) AlterColumn(ctx context.Context, name string, c ColumnChanges) error {
	if name == "" {
		return invalidf("pgmo: alter column: no name")
	}
	return t.alter(ctx, "alter column "+pgsql.QuoteIdent(name)+" of", func() (string, error) {
		acts, err := c.actions(pgsql.QuoteIdent(name))
		return strings.Join(acts, ", "), err
	})
}

// SetColumnComment sets the column name's comment (COMMENT ON COLUMN), ""
// removing it.
func (t *Table) SetColumnComment(ctx context.Context, name, text string) error {
	if name == "" {
		return invalidf("pgmo: comment on column: no name")
	}
	o, err := t.ddl("comment on column " + pgsql.QuoteIdent(name) + " of")
	if err != nil {
		return err
	}
	return o.do(ctx, "comment on column "+pgsql.QuoteIdent(name)+" of", commentStatement("COLUMN "+o.name+"."+pgsql.QuoteIdent(name), text))
}

