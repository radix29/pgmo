// ============================================================
// Table writes
// ============================================================
//
// table_write.go is P4.13.3's tables: CREATE TABLE from a request (columns,
// constraints, inheritance, partitioning), DROP TABLE (CASCADE opt-in),
// ALTER TABLE's RENAME TO, SET SCHEMA, OWNER TO and its column and
// constraint forms, COMMENT ON TABLE / COLUMN / CONSTRAINT. Every statement
// runs on the database's own session and may run inside InTransaction.
//
// A column's type, a default, a generation or check expression and a
// partitioning clause are SQL the caller writes, and are written as given;
// every name is quoted (object_write.go).

// ColumnSpec is one column of CreateTable or AddColumn.
type ColumnSpec struct {
	Name string

	// Type is the column's type as SQL writes it, modifier included:
	// "integer", "numeric(18,2)", "app.mood[]". It is written as given —
	// qualify a type outside pg_catalog, or it resolves through the
	// session's search_path. Column.Type reads back in this form.
	Type string

	// Collation is COLLATE: the column's collation when it is not its
	// type's own; zero for none.
	Collation ObjectName

	// NotNull is NOT NULL.
	NotNull bool

	// Default is DEFAULT's expression, as SQL ("now()", "'x'::text", "0");
	// "" for none. Not with Identity or Generated.
	Default string

	// Identity is GENERATED ALWAYS AS IDENTITY (IdentityAlways) or
	// GENERATED BY DEFAULT AS IDENTITY (IdentityByDefault); the server
	// makes the column NOT NULL and gives it a sequence of its own.
	Identity IdentityKind

	// Generated and GenerationExpression make a generated column:
	// GENERATED ALWAYS AS (expression) STORED, or VIRTUAL (18+).
	Generated            GeneratedKind
	GenerationExpression string
}

// definition is the column definition c writes on a server at num, or the
// refusal of one that cannot be written. No prefix: the caller names the
// operation.
func (c ColumnSpec) definition(num int) (string, error) {
	if c.Name == "" {
		return "", invalidf("a column with no name")
	}
	if c.Type == "" {
		return "", invalidf("column %s: no type", pgsql.QuoteIdent(c.Name))
	}
	col := pgsql.QuoteIdent(c.Name)
	switch c.Identity {
	case IdentityNone, IdentityAlways, IdentityByDefault:
	default:
		return "", invalidf("column %s: unknown identity kind %q", col, string(c.Identity))
	}
	switch c.Generated {
	case GeneratedNone:
		if c.GenerationExpression != "" {
			return "", invalidf("column %s: a generation expression with no Generated kind", col)
		}
	case GeneratedStored, GeneratedVirtual:
		if c.GenerationExpression == "" {
			return "", invalidf("column %s: generated with no expression", col)
		}
		if c.Generated == GeneratedVirtual && before(num, PostgreSQL18) {
			return "", refusalf(ErrUnsupportedVersion, "column %s: a virtual generated column needs %s or later; the server is %s", col, PostgreSQL18, ServerVersion(num))
		}
	default:
		return "", invalidf("column %s: unknown generated kind %q", col, string(c.Generated))
	}
	n := 0
	for _, set := range []bool{c.Default != "", c.Identity != IdentityNone, c.Generated != GeneratedNone} {
		if set {
			n++
		}
	}
	if n > 1 {
		return "", invalidf("column %s: a default, an identity and a generation expression exclude one another", col)
	}

	def := col + " " + c.Type
	if c.Collation.Name != "" {
		def += " COLLATE " + c.Collation.QualifiedName()
	}
	switch {
	case c.Identity == IdentityAlways:
		def += " GENERATED ALWAYS AS IDENTITY"
	case c.Identity == IdentityByDefault:
		def += " GENERATED BY DEFAULT AS IDENTITY"
	case c.Generated == GeneratedStored:
		def += " GENERATED ALWAYS AS (" + c.GenerationExpression + ") STORED"
	case c.Generated == GeneratedVirtual:
		def += " GENERATED ALWAYS AS (" + c.GenerationExpression + ") VIRTUAL"
	case c.Default != "":
		def += " DEFAULT " + c.Default
	}
	if c.NotNull {
		def += " NOT NULL"
	}
	return def, nil
}

// ConstraintSpec is one table constraint of CreateTable or AddConstraint:
// its Kind decides which of the other fields it takes, and a field another
// kind's is refused rather than left out.
type ConstraintSpec struct {
	// Name is CONSTRAINT's name; "" lets the server pick one
	// (table_column_pkey, table_column_check…).
	Name string

	// Kind is ConstraintPrimaryKey, ConstraintUnique, ConstraintForeignKey,
	// ConstraintCheck or ConstraintExclusion. A NOT NULL constraint is the
	// column's: ColumnSpec.NotNull, ColumnChanges.NotNull.
	Kind ConstraintKind

	// Columns are a key's columns: a primary key's, a unique constraint's,
	// a foreign key's referencing ones.
	Columns []string

	// Include are a primary key's or unique constraint's INCLUDE columns,
	// stored in its index but not part of the key.
	Include []string

	// NullsNotDistinct is a unique constraint's NULLS NOT DISTINCT: NULLs
	// count as equal, so only one is allowed.
	NullsNotDistinct bool

	// Check is a check constraint's expression, as SQL, without CHECK's
	// parentheses; NoInherit is its NO INHERIT.
	Check     string
	NoInherit bool

	// ReferencedTable and ReferencedColumns are a foreign key's REFERENCES
	// (the referenced table's primary key when no columns); Match, OnUpdate
	// and OnDelete its MATCH and actions, "" for the server's (SIMPLE, NO
	// ACTION).
	ReferencedTable   ObjectName
	ReferencedColumns []string
	Match             ForeignKeyMatch
	OnUpdate          ForeignKeyAction
	OnDelete          ForeignKeyAction

	// Exclude is an exclusion constraint's body after EXCLUDE, as SQL:
	// "USING gist (room WITH =, during WITH &&)".
	Exclude string

	// Deferrable and InitiallyDeferred are DEFERRABLE and INITIALLY
	// DEFERRED: keys, foreign keys and exclusions only.
	Deferrable        bool
	InitiallyDeferred bool

	// NotValid is NOT VALID: a foreign key or check added to a table
	// without checking its rows, enforced on new rows only until
	// Table.ValidateConstraint. AddConstraint only: CREATE TABLE accepts the
	// words and then validates the constraint anyway, so it is refused there.
	NotValid bool

	// NotEnforced is NOT ENFORCED (18+): a foreign key or check that is
	// declared but never checked.
	NotEnforced bool
}

// definition is the table constraint c writes on a server at num, or the
// refusal of one that cannot be written. No prefix: the caller names the
// operation.
func (c ConstraintSpec) definition(num int) (string, error) {
	var body string
	refuse := func(field string, set bool) error {
		if set {
			return invalidf("%s takes no %s", c.Kind, field)
		}
		return nil
	}
	keyed := c.Kind == ConstraintPrimaryKey || c.Kind == ConstraintUnique
	checks := []error{
		refuse("columns", len(c.Columns) > 0 && c.Kind != ConstraintForeignKey && !keyed),
		refuse("INCLUDE columns", len(c.Include) > 0 && !keyed),
		refuse("NULLS NOT DISTINCT", c.NullsNotDistinct && c.Kind != ConstraintUnique),
		refuse("check expression", c.Check != "" && c.Kind != ConstraintCheck),
		refuse("NO INHERIT", c.NoInherit && c.Kind != ConstraintCheck),
		refuse("REFERENCES", (c.ReferencedTable != ObjectName{} || len(c.ReferencedColumns) > 0 ||
			c.Match != "" || c.OnUpdate != "" || c.OnDelete != "") && c.Kind != ConstraintForeignKey),
		refuse("EXCLUDE body", c.Exclude != "" && c.Kind != ConstraintExclusion),
		refuse("DEFERRABLE", (c.Deferrable || c.InitiallyDeferred) && c.Kind == ConstraintCheck),
		refuse("NOT VALID", c.NotValid && c.Kind != ConstraintCheck && c.Kind != ConstraintForeignKey),
		refuse("NOT ENFORCED", c.NotEnforced && c.Kind != ConstraintCheck && c.Kind != ConstraintForeignKey),
	}
	for _, err := range checks {
		if err != nil {
			return "", err
		}
	}
	if err := requireNames("the constraint's columns", slices.Concat(c.Columns, c.Include, c.ReferencedColumns)); err != nil {
		return "", err
	}
	include := ""
	if len(c.Include) > 0 {
		include = " INCLUDE (" + identList(c.Include) + ")"
	}
	switch c.Kind {
	case ConstraintPrimaryKey, ConstraintUnique:
		if len(c.Columns) == 0 {
			return "", invalidf("%s with no columns", c.Kind)
		}
		body = c.Kind.String()
		if c.NullsNotDistinct {
			body += " NULLS NOT DISTINCT"
		}
		body += " (" + identList(c.Columns) + ")" + include
	case ConstraintCheck:
		if c.Check == "" {
			return "", invalidf("CHECK with no expression")
		}
		body = "CHECK (" + c.Check + ")"
		if c.NoInherit {
			body += " NO INHERIT"
		}
	case ConstraintForeignKey:
		if len(c.Columns) == 0 {
			return "", invalidf("FOREIGN KEY with no columns")
		}
		if err := checkQualified("references", c.ReferencedTable.Schema, c.ReferencedTable.Name); err != nil {
			return "", err
		}
		body = "FOREIGN KEY (" + identList(c.Columns) + ") REFERENCES " + c.ReferencedTable.QualifiedName()
		if len(c.ReferencedColumns) > 0 {
			body += " (" + identList(c.ReferencedColumns) + ")"
		}
		switch c.Match {
		case "":
		case ForeignKeyMatchSimple, ForeignKeyMatchFull, ForeignKeyMatchPartial:
			body += " MATCH " + c.Match.String()
		default:
			return "", invalidf("unknown foreign key match type %q", string(c.Match))
		}
		for _, a := range []struct {
			on     string
			action ForeignKeyAction
		}{{"DELETE", c.OnDelete}, {"UPDATE", c.OnUpdate}} {
			switch a.action {
			case "":
			case ForeignKeyNoAction, ForeignKeyRestrict, ForeignKeyCascade, ForeignKeySetNull, ForeignKeySetDefault:
				body += " ON " + a.on + " " + a.action.String()
			default:
				return "", invalidf("unknown foreign key action %q", string(a.action))
			}
		}
	case ConstraintExclusion:
		if c.Exclude == "" {
			return "", invalidf("EXCLUDE with no body")
		}
		body = "EXCLUDE " + c.Exclude
	case ConstraintNotNull:
		return "", invalidf("a NOT NULL constraint is the column's: ColumnSpec.NotNull, ColumnChanges.NotNull")
	default:
		return "", invalidf("unknown constraint kind %q", string(c.Kind))
	}
	if c.NotEnforced && before(num, PostgreSQL18) {
		return "", refusalf(ErrUnsupportedVersion, "NOT ENFORCED needs %s or later; the server is %s", PostgreSQL18, ServerVersion(num))
	}

	def := ""
	if c.Name != "" {
		def = "CONSTRAINT " + pgsql.QuoteIdent(c.Name) + " "
	}
	def += body
	if c.Deferrable {
		def += " DEFERRABLE"
	}
	if c.InitiallyDeferred {
		def += " INITIALLY DEFERRED"
	}
	if c.NotEnforced {
		def += " NOT ENFORCED"
	}
	if c.NotValid {
		def += " NOT VALID"
	}
	return def, nil
}

// CreateTableRequest describes a new table: an ordinary one with Columns
// (and Inherits, or PartitionBy for a partitioned one), or a partition of
// an existing partitioned table with PartitionOf and PartitionBound.
type CreateTableRequest struct {
	Schema, Name string

	// Unlogged is UNLOGGED: the table's data is not WAL-logged — faster to
	// write, emptied by crash recovery, not replicated.
	Unlogged bool

	// Columns are the table's columns, in order; none is a table with no
	// columns, which PostgreSQL allows. A partition takes its parent's and
	// is refused any.
	Columns []ColumnSpec

	// Constraints are the table's constraints, after the columns.
	Constraints []ConstraintSpec

	// Inherits are the tables it inherits from (INHERITS), in order.
	Inherits []ObjectName

	// PartitionBy makes a partitioned table: PARTITION BY's clause as SQL,
	// "RANGE (at)", "LIST (region)", "HASH (id)".
	PartitionBy string

	// PartitionOf and PartitionBound make a partition of a partitioned
	// table: PARTITION OF parent and its bound as SQL — "FOR VALUES FROM
	// ('2026-01-01') TO ('2027-01-01')", "FOR VALUES IN ('eu')", "FOR
	// VALUES WITH (MODULUS 4, REMAINDER 0)", or "DEFAULT".
	PartitionOf    ObjectName
	PartitionBound string

	// Tablespace is TABLESPACE; "" is the database's default.
	Tablespace string

	// Options are the storage parameters (WITH (fillfactor = '70', …)), as
	// Table.Options reads them: a "toast." prefix for the TOAST table's.
	Options []ParameterSetting
}

// createTableStatement is req's CREATE TABLE on a server at num, or the
// refusal of a request that cannot be written. No prefix: the caller names
// the operation.
func createTableStatement(num int, req CreateTableRequest) (string, error) {
	partition := req.PartitionOf != ObjectName{}
	switch {
	case partition && len(req.Columns) > 0:
		return "", invalidf("a partition takes its parent's columns; it is given none")
	case partition && len(req.Inherits) > 0:
		return "", invalidf("a partition inherits from its parent alone")
	case partition && req.PartitionBound == "":
		return "", invalidf("a partition with no bound (PartitionBound: FOR VALUES …, or DEFAULT)")
	case !partition && req.PartitionBound != "":
		return "", invalidf("a partition bound with no parent (PartitionOf)")
	}
	var elems []string
	for _, c := range req.Columns {
		def, err := c.definition(num)
		if err != nil {
			return "", err
		}
		elems = append(elems, def)
	}
	for _, c := range req.Constraints {
		if c.NotValid {
			return "", invalidf("NOT VALID in CREATE TABLE: the server validates the constraint anyway; add it with AddConstraint")
		}
		def, err := c.definition(num)
		if err != nil {
			return "", err
		}
		elems = append(elems, def)
	}
	opts, err := storageParameters(req.Options)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("CREATE ")
	if req.Unlogged {
		b.WriteString("UNLOGGED ")
	}
	b.WriteString("TABLE " + pgsql.QualifiedName(req.Schema, req.Name))
	if partition {
		if err := checkQualified("partition of", req.PartitionOf.Schema, req.PartitionOf.Name); err != nil {
			return "", err
		}
		b.WriteString(" PARTITION OF " + req.PartitionOf.QualifiedName())
		if len(elems) > 0 {
			b.WriteString(" (" + strings.Join(elems, ", ") + ")")
		}
		b.WriteString(" " + req.PartitionBound)
	} else {
		b.WriteString(" (" + strings.Join(elems, ", ") + ")")
		if len(req.Inherits) > 0 {
			parents := make([]string, len(req.Inherits))
			for i, p := range req.Inherits {
				if err := checkQualified("inherits", p.Schema, p.Name); err != nil {
					return "", err
				}
				parents[i] = p.QualifiedName()
			}
			b.WriteString(" INHERITS (" + strings.Join(parents, ", ") + ")")
		}
	}
	if req.PartitionBy != "" {
		b.WriteString(" PARTITION BY " + req.PartitionBy)
	}
	if opts != "" {
		b.WriteString(" WITH " + opts)
	}
	if req.Tablespace != "" {
		b.WriteString(" TABLESPACE " + pgsql.QuoteIdent(req.Tablespace))
	}
	return b.String(), nil
}

// CreateTable creates the table req describes, and returns it read back from
// the catalog — or, under Scripting(ctx), the TableRef handle. A virtual
// generated column and NOT ENFORCED (both before 18) are refused with
// ErrUnsupportedVersion before anything is sent. The role needs CREATE on
// the schema, and ownership of a parent.
func (d *Database) CreateTable(ctx context.Context, req CreateTableRequest) (*Table, error) {
	if err := requireQualified("create table", req.Schema, req.Name); err != nil {
		return nil, err
	}
	op := "create table " + pgsql.QualifiedName(req.Schema, req.Name)
	stmt, err := createTableStatement(int(d.server.version), req)
	if err != nil {
		return nil, fmt.Errorf("pgmo: %s: %w", op, err)
	}
	if err := d.exec(ctx, stmt); err != nil {
		return nil, fmt.Errorf("pgmo: %s: %w", op, err)
	}
	return createdObject(ctx, d.TableRef(req.Schema, req.Name), func() (*Table, error) {
		return d.TableByName(ctx, req.Schema, req.Name)
	})
}

// ddl is the table's DDL handle for verb, or the refusal of one missing its
// schema or name.
func (t *Table) ddl(verb string) (ddlObject, error) {
	return t.db.qualified(verb, "TABLE", t.Schema, t.Name)
}

// alter runs ALTER TABLE t <action> as the operation verb ("add column
// to"); action builds the subcommand, or refuses it.
func (t *Table) alter(ctx context.Context, verb string, action func() (string, error)) error {
	o, err := t.ddl(verb)
	if err != nil {
		return err
	}
	act, err := action()
	if err != nil {
		return fmt.Errorf("pgmo: %s: %w", o.op(verb), err)
	}
	if act == "" {
		return nil
	}
	return o.do(ctx, verb, "ALTER TABLE "+o.name+" "+act)
}

// fixed is an alter action that cannot be refused.
func fixed(action string) func() (string, error) {
	return func() (string, error) { return action, nil }
}

// Drop drops the table: DROP TABLE, with CASCADE when opts.Cascade — which
// drops the views over it and the foreign keys referencing it (the
// referencing tables stay). A partitioned table's partitions go with it.
func (t *Table) Drop(ctx context.Context, opts DropOptions) error {
	return dropObject(ctx, t.ddl, opts)
}

// Rename renames the table (ALTER TABLE … RENAME TO), mirrored onto Name
// (not under WithScript). It stays in its schema.
func (t *Table) Rename(ctx context.Context, newName string) error {
	return renameObject(ctx, t.ddl, newName, &t.Name)
}

// SetSchema moves the table to schema (ALTER TABLE … SET SCHEMA), with its
// indexes, constraints and owned sequences; mirrored onto Schema (not under
// WithScript).
func (t *Table) SetSchema(ctx context.Context, schema string) error {
	return moveObject(ctx, t.ddl, schema, &t.Schema)
}

// SetOwner makes role the table's owner (ALTER TABLE … OWNER TO), with its
// indexes and owned sequences; mirrored onto Owner (not under WithScript).
func (t *Table) SetOwner(ctx context.Context, role string) error {
	return ownObject(ctx, t.ddl, role, &t.Owner)
}

// SetComment sets the table's comment (COMMENT ON TABLE), "" removing it,
// mirrored onto Comment (not under WithScript).
func (t *Table) SetComment(ctx context.Context, text string) error {
	return commentObject(ctx, t.ddl, text, &t.Comment)
}

